-- Records administrator changes to an account's role or status (who changed whose role/status
-- and when) so those privileged actions stay traceable after the fact.
CREATE TABLE admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL,
    previous_value VARCHAR(50),
    new_value VARCHAR(50),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_admin_audit_logs_action CHECK (action IN ('STATUS_CHANGE', 'ROLE_CHANGE')),
    CONSTRAINT fk_admin_audit_logs_actor FOREIGN KEY (actor_id) REFERENCES users(id),
    CONSTRAINT fk_admin_audit_logs_target FOREIGN KEY (target_id) REFERENCES users(id)
);

CREATE INDEX idx_admin_audit_logs_target ON admin_audit_logs (target_id, created_at);
CREATE INDEX idx_admin_audit_logs_created_at ON admin_audit_logs (created_at);
