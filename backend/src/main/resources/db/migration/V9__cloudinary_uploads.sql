-- Records every Cloudinary upload signature issued so per-user quotas can be enforced and
-- issued public ids can be audited. The files themselves live in Cloudinary; only the
-- metadata needed for quotas is stored here.
CREATE TABLE cloudinary_uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    public_id VARCHAR(36) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_cloudinary_uploads_public_id UNIQUE (public_id),
    CONSTRAINT fk_cloudinary_uploads_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_cloudinary_uploads_user_created ON cloudinary_uploads (user_id, created_at);
