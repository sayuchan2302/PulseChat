-- Stores browser Web Push subscriptions (VAPID RFC 8291/8292) so users can receive
-- notifications for incoming messages and calls even when the tab is closed.
CREATE TABLE web_push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    endpoint VARCHAR(1024) NOT NULL,
    p256dh VARCHAR(255) NOT NULL,
    auth VARCHAR(255) NOT NULL,
    user_agent VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_web_push_endpoint UNIQUE (endpoint),
    CONSTRAINT fk_web_push_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_web_push_user_id ON web_push_subscriptions (user_id);

