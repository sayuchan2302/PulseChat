-- Initial production schema. Existing databases are baselined at version 1;
-- this migration creates the schema for new production databases.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    full_name VARCHAR(100),
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    avatar VARCHAR(255),
    bio VARCHAR(160),
    online BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE chat_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    avatar VARCHAR(500),
    invite_code VARCHAR(64),
    invite_code_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    owner_id BIGINT,
    pinned_message_id BIGINT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_chat_rooms_invite_code UNIQUE (invite_code),
    CONSTRAINT ck_chat_rooms_type CHECK (type IN ('PRIVATE', 'GROUP')),
    CONSTRAINT fk_chat_rooms_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);

CREATE TABLE chat_room_participants (
    chat_room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    nickname VARCHAR(80),
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT pk_chat_room_participants PRIMARY KEY (chat_room_id, user_id),
    CONSTRAINT uk_chat_room_participant UNIQUE (chat_room_id, user_id),
    CONSTRAINT ck_chat_room_participants_role CHECK (role IN ('OWNER', 'MODERATOR', 'MEMBER')),
    CONSTRAINT fk_chat_room_participants_room FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id),
    CONSTRAINT fk_chat_room_participants_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE call_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT ck_call_sessions_type CHECK (type IN ('AUDIO', 'VIDEO')),
    CONSTRAINT ck_call_sessions_status CHECK (status IN ('RINGING', 'ACCEPTED', 'REJECTED', 'MISSED', 'ENDED', 'CANCELED', 'BUSY')),
    CONSTRAINT fk_call_sessions_caller FOREIGN KEY (caller_id) REFERENCES users(id),
    CONSTRAINT fk_call_sessions_receiver FOREIGN KEY (receiver_id) REFERENCES users(id)
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(5000) NOT NULL,
    type VARCHAR(20),
    media_url VARCHAR(2048),
    media_public_id VARCHAR(255),
    media_resource_type VARCHAR(20),
    media_format VARCHAR(20),
    media_bytes BIGINT,
    media_width INTEGER,
    media_height INTEGER,
    media_duration DOUBLE PRECISION,
    link_preview_url VARCHAR(2048),
    link_preview_title VARCHAR(255),
    link_preview_description VARCHAR(500),
    link_preview_image_url VARCHAR(2048),
    link_preview_domain VARCHAR(255),
    client_id VARCHAR(100),
    sender_id BIGINT NOT NULL,
    receiver_id BIGINT,
    chat_room_id BIGINT,
    reply_to_message_id BIGINT,
    forwarded_from_id BIGINT,
    call_session_id BIGINT,
    recalled BOOLEAN NOT NULL DEFAULT FALSE,
    read BOOLEAN NOT NULL DEFAULT FALSE,
    timestamp TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT fk_messages_receiver FOREIGN KEY (receiver_id) REFERENCES users(id),
    CONSTRAINT fk_messages_chat_room FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id),
    CONSTRAINT fk_messages_reply_to FOREIGN KEY (reply_to_message_id) REFERENCES messages(id),
    CONSTRAINT fk_messages_forwarded_from FOREIGN KEY (forwarded_from_id) REFERENCES messages(id),
    CONSTRAINT fk_messages_call_session FOREIGN KEY (call_session_id) REFERENCES call_sessions(id),
    CONSTRAINT messages_type_check CHECK (type IS NULL OR type IN ('TEXT', 'IMAGE', 'VIDEO', 'AUDIO', 'FILE', 'CALL'))
);

ALTER TABLE chat_rooms
    ADD CONSTRAINT fk_chat_rooms_pinned_message FOREIGN KEY (pinned_message_id) REFERENCES messages(id);

CREATE TABLE message_reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    emoji VARCHAR(32) NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_message_reaction_user UNIQUE (message_id, user_id),
    CONSTRAINT fk_message_reactions_message FOREIGN KEY (message_id) REFERENCES messages(id),
    CONSTRAINT fk_message_reactions_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE message_mentions (
    message_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT pk_message_mentions PRIMARY KEY (message_id, user_id),
    CONSTRAINT fk_message_mentions_message FOREIGN KEY (message_id) REFERENCES messages(id),
    CONSTRAINT fk_message_mentions_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE friendships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    user_low_id BIGINT NOT NULL,
    user_high_id BIGINT NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_friendships_user_pair UNIQUE (user_low_id, user_high_id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users(id),
    CONSTRAINT fk_friendships_receiver FOREIGN KEY (receiver_id) REFERENCES users(id)
);

CREATE TABLE conversation_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    target_user_id BIGINT,
    chat_room_id BIGINT,
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    muted BOOLEAN NOT NULL DEFAULT FALSE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    pinned_message_id BIGINT,
    cleared_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_conversation_settings_private UNIQUE (user_id, target_user_id),
    CONSTRAINT uk_conversation_settings_room UNIQUE (user_id, chat_room_id),
    CONSTRAINT fk_conversation_settings_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_conversation_settings_target_user FOREIGN KEY (target_user_id) REFERENCES users(id),
    CONSTRAINT fk_conversation_settings_room FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id)
);

CREATE TABLE chat_room_read_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    last_read_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_chat_room_read_state_room_user UNIQUE (chat_room_id, user_id),
    CONSTRAINT fk_chat_room_read_states_room FOREIGN KEY (chat_room_id) REFERENCES chat_rooms(id),
    CONSTRAINT fk_chat_room_read_states_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users(id)
);

