-- Tracks every local media upload so per-user quotas can be enforced and abandoned uploads
-- (never referenced by a message or an avatar) can be deleted after a grace period.
CREATE TABLE media_uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    public_id VARCHAR(36) NOT NULL,
    format VARCHAR(20) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_media_uploads_public_id UNIQUE (public_id),
    CONSTRAINT fk_media_uploads_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_media_uploads_user_created ON media_uploads (user_id, created_at);
